// Builds responsive WebP files from media-src/ into public/img/ and writes app/data/images.generated.js.
// Run after adding or replacing photos: `npm run images`. Already-built files are skipped.
// Usage: node scripts/images.mjs [--force]
import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = path.join(ROOT, 'media-src');
const OUT = path.join(ROOT, 'public/img');
const MANIFEST = path.join(ROOT, 'app/data/images.generated.js');
const FORCE = process.argv.includes('--force');

const PHOTO_WIDTHS = [480, 960, 1600, 2400];
const LOGO_WIDTHS = [160, 320];
const MIN_WIDTH = 300; // smaller photos are skipped and reported (logos are always kept)

async function walk(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)])),
  );
  return files.flat().filter((f) => /\.(jpe?g|png|webp)$/i.test(f));
}

const exists = (p) => fs.access(p).then(() => true, () => false);
const hex = ({ r, g, b }) => '#' + [r, g, b].map((v) => v.toString(16).padStart(2, '0')).join('');

const files = (await walk(SRC)).sort();
const manifest = {};
const skipped = [];
const small = [];

for (const file of files) {
  const id = path.relative(SRC, file).replace(/\\/g, '/').replace(/\.[^.]+$/, '');
  const img = sharp(file).rotate(); // honour EXIF orientation
  const meta = await img.metadata();
  const swap = (meta.orientation ?? 1) >= 5;
  const w = swap ? meta.height : meta.width;
  const h = swap ? meta.width : meta.height;
  const isLogo = id.startsWith('clients/') || id.startsWith('branding/');
  if (!isLogo && w < MIN_WIDTH) {
    skipped.push(`${id} (${w}px)`);
    continue;
  }
  const steps = isLogo ? LOGO_WIDTHS : PHOTO_WIDTHS;
  let widths = steps.filter((s) => s < w);
  if (widths.length === 0 || (w < steps.at(-1) && w - widths.at(-1) > 120)) widths.push(w);
  widths = widths.slice(0, steps.length);

  await fs.mkdir(path.dirname(path.join(OUT, id)), { recursive: true });
  for (const width of widths) {
    const out = path.join(OUT, `${id}-${width}.webp`);
    if (!FORCE && (await exists(out))) continue;
    await sharp(file).rotate().resize({ width, withoutEnlargement: true }).webp({ quality: isLogo ? 85 : 70, effort: 5 }).toFile(out);
  }
  const { dominant } = await sharp(file).stats();
  manifest[id] = { w, h, widths, color: hex(dominant) };
  if (!isLogo && w < 1200) small.push(`${id} (${w}px)`);
}

const body =
  '// GENERATED by scripts/images.mjs. Do not edit by hand; run `npm run images`.\n' +
  '// id → { w, h, widths: built WebP widths, color: dominant colour used as the loading placeholder }\n' +
  `export const images = ${JSON.stringify(manifest, null, 0).replace(/\},"/g, '},\n  "')};\n`;
await fs.writeFile(MANIFEST, body);

console.log(`images: ${Object.keys(manifest).length} written to public/img`);
if (skipped.length) console.log(`skipped (< ${MIN_WIDTH}px wide): ${skipped.join(', ')}`);
console.log(`under 1200px wide (never use full-bleed): ${small.length}\n  ${small.join('\n  ')}`);
